create table flights (
    id bigint generated by default as identity primary key,
    airline_id bigint not null references airlines(id),
    flight_number varchar(20) not null,
    flight_date date not null,
    aircraft_id bigint not null references aircraft(id),
    departure_airport_id bigint not null references airports(id),
    arrival_airport_id bigint not null references airports(id),
    departure_time timestamp with time zone not null,
    arrival_time timestamp with time zone not null,
    departure_terminal varchar(20),
    departure_gate varchar(20),
    arrival_terminal varchar(20),
    arrival_gate varchar(20),
    status varchar(30) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint uq_flights_number_date unique (flight_number, flight_date)
);
