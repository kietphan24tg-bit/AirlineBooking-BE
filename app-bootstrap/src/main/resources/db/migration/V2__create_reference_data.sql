create table airports (
    id bigint generated by default as identity primary key,
    code varchar(10) not null unique,
    name varchar(255) not null,
    city varchar(150) not null,
    country varchar(150) not null,
    time_zone varchar(100) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create table airlines (
    id bigint generated by default as identity primary key,
    code varchar(10) not null unique,
    name varchar(255) not null,
    logo_url varchar(500),
    created_at timestamp with time zone not null default current_timestamp
);

create table aircraft (
    id bigint generated by default as identity primary key,
    model varchar(150) not null,
    manufacturer varchar(150) not null,
    total_seats integer not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create table seats (
    id bigint generated by default as identity primary key,
    aircraft_id bigint not null references aircraft(id),
    seat_number varchar(10) not null,
    seat_class varchar(30) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint uq_seats_aircraft_seat_number unique (aircraft_id, seat_number)
);

create table fare_classes (
    id bigint generated by default as identity primary key,
    code varchar(30) not null unique,
    name varchar(100) not null,
    cabin_class varchar(30) not null,
    baggage_checkin_kg integer not null default 0,
    baggage_hand_kg integer not null default 0,
    change_fee numeric(18, 2) not null default 0,
    refund_fee numeric(18, 2) not null default 0,
    is_refundable boolean not null default false,
    is_changeable boolean not null default false,
    is_priority_checkin boolean not null default false,
    is_priority_boarding boolean not null default false,
    mileage_rate numeric(8, 2) not null default 0,
    description text,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create table tax_fees (
    id bigint generated by default as identity primary key,
    code varchar(50) not null unique,
    name varchar(255) not null,
    amount_type varchar(20) not null,
    value numeric(18, 2) not null,
    apply_to varchar(20) not null,
    description text,
    is_active boolean not null default true,
    created_at timestamp with time zone not null default current_timestamp
);

create table promotions (
    id bigint generated by default as identity primary key,
    code varchar(50) not null unique,
    description text,
    discount_type varchar(20) not null,
    discount_value numeric(18, 2) not null,
    max_discount numeric(18, 2),
    min_booking_amount numeric(18, 2),
    usage_limit integer,
    used_count integer not null default 0,
    is_active boolean not null default true,
    starts_at timestamp with time zone,
    expires_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp
);

create table services (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    type varchar(30) not null,
    icon_url varchar(500),
    is_active boolean not null default true
);

create table service_options (
    id bigint generated by default as identity primary key,
    service_id bigint not null references services(id),
    name varchar(255) not null,
    description text,
    price numeric(18, 2) not null default 0,
    image_url varchar(500),
    is_active boolean not null default true
);
