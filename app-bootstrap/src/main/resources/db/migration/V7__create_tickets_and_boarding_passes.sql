create table tickets (
    id bigint generated by default as identity primary key,
    booking_id bigint not null references bookings(id),
    flight_fare_id bigint not null references flight_fares(id),
    passenger_id bigint not null references passengers(id),
    flight_id bigint not null references flights(id),
    flight_seat_id bigint references flight_seats(id),
    fare_class_id bigint not null references fare_classes(id),
    ticket_number varchar(50) not null unique,
    status varchar(30) not null,
    issued_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint uq_tickets_passenger_flight unique (passenger_id, flight_id)
);

create table boarding_passes (
    id bigint generated by default as identity primary key,
    ticket_id bigint not null unique references tickets(id),
    qr_code text not null,
    gate varchar(20),
    boarding_time timestamp with time zone,
    sequence_number integer,
    seat_label varchar(10),
    is_boarded boolean not null default false,
    boarded_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp
);
