alter table payments
    add column updated_at timestamp with time zone not null default current_timestamp;

update payments
set updated_at = coalesce(paid_at, created_at, current_timestamp)
where updated_at is null;

create table payment_webhook_events (
    id bigint generated by default as identity primary key,
    provider varchar(30) not null,
    idempotency_key varchar(255) not null,
    payment_id bigint references payments(id),
    booking_id bigint references bookings(id),
    transaction_id varchar(100),
    order_code bigint,
    event_type varchar(40) not null,
    processing_status varchar(30) not null,
    is_final boolean not null default true,
    signature varchar(255),
    signature_valid boolean not null,
    raw_payload text not null,
    error_code varchar(80),
    error_message varchar(255),
    received_at timestamp with time zone not null default current_timestamp,
    processed_at timestamp with time zone
);

create unique index uq_payment_webhook_events_provider_key
    on payment_webhook_events(provider, idempotency_key);

create index idx_payment_webhook_events_payment_received
    on payment_webhook_events(payment_id, received_at desc);

create index idx_payment_webhook_events_transaction
    on payment_webhook_events(transaction_id);
