create table if not exists seat_classes (
    id bigint generated by default as identity primary key,
    code varchar(30) not null unique,
    name varchar(100) not null
);

create table if not exists seat_types (
    id bigint generated by default as identity primary key,
    code varchar(30) not null unique
);

insert into seat_classes (code, name)
values ('ECONOMY', 'Economy'),
       ('BUSINESS', 'Business')
on conflict (code) do nothing;

insert into seat_types (code)
values ('WINDOW'),
       ('AISLE'),
       ('MIDDLE')
on conflict (code) do nothing;

create table if not exists fare_class_seat_classes (
    id bigint generated by default as identity primary key,
    fare_class_id bigint not null references fare_classes(id),
    seat_class_id bigint not null references seat_classes(id),
    constraint uq_fare_class_seat_classes unique (fare_class_id, seat_class_id)
);

alter table flight_seats
    add column if not exists seat_class_id bigint references seat_classes(id),
    add column if not exists seat_type_id bigint references seat_types(id);

update flight_seats fs
set seat_class_id = sc.id
from seat_classes sc
where fs.seat_class_id is null
  and upper(coalesce(fs.seat_class, '')) = sc.code;

update flight_seats fs
set seat_class_id = sc.id
from seat_classes sc
where fs.seat_class_id is null
  and sc.code = 'ECONOMY';

update flight_seats fs
set seat_type_id = st.id
from seat_types st
where fs.seat_type_id is null
  and st.code = 'MIDDLE';

alter table flight_seats
    alter column seat_class_id set not null,
    alter column seat_type_id set not null;

alter table flight_seats
    drop column if exists seat_class,
    drop column if exists passenger_id,
    drop column if exists price;

alter table flight_seats
    drop constraint if exists chk_flight_seats_status;

update flight_seats
set status = 'LOCKED'
where status = 'RESERVED';

alter table flight_seats
    add constraint chk_flight_seats_status
        check (status in ('AVAILABLE', 'LOCKED', 'BOOKED'));

drop index if exists idx_flight_seats_fare_class_id;
create index if not exists idx_flight_seats_fare_class_id on flight_seats(fare_class_id);
create index if not exists idx_flight_seats_seat_class_id on flight_seats(seat_class_id);
