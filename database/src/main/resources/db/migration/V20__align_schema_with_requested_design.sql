create table if not exists aircraft_layout (
    id bigint generated by default as identity primary key,
    aircraft_id bigint not null references aircraft(id),
    total_rows integer not null,
    columns varchar(10) not null,
    business_rows integer not null,
    created_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_airports_country on airports(country);

alter table flights
    drop constraint if exists uq_flights_number_date;

alter table flights
    add constraint uq_flights_airline_number_date unique (airline_id, flight_number, flight_date);

create index if not exists idx_flights_departure_airport_id on flights(departure_airport_id);
create index if not exists idx_flights_arrival_airport_id on flights(arrival_airport_id);
create index if not exists idx_flights_departure_time on flights(departure_time);

alter table flight_seats
    add column if not exists seat_number varchar(10),
    add column if not exists seat_class varchar(30);

update flight_seats fs
set seat_number = s.seat_number,
    seat_class = s.seat_class
from seats s
where fs.seat_id = s.id
  and (fs.seat_number is null or fs.seat_class is null);

alter table flight_seats
    alter column seat_number set not null,
    alter column seat_class set not null;

update flight_seats
set status = 'LOCKED'
where status = 'BLOCKED';

alter table flight_seats
    drop constraint if exists chk_flight_seats_status;

alter table flight_seats
    add constraint chk_flight_seats_status
        check (status in ('AVAILABLE', 'LOCKED', 'BOOKED', 'RESERVED'));

create unique index if not exists uq_flight_seats_flight_seat_number on flight_seats(flight_id, seat_number);
create index if not exists idx_flight_seats_flight_id on flight_seats(flight_id);
create index if not exists idx_flight_seats_fare_class_id on flight_seats(fare_class_id);
