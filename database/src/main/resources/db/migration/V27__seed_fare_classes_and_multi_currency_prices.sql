create table if not exists fare_class_prices (
    id bigint generated by default as identity primary key,
    fare_class_id bigint not null references fare_classes(id),
    currency varchar(3) not null,
    country_code varchar(2) not null default 'GL',
    base_price numeric(18, 2) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint chk_fare_class_prices_currency_upper check (currency = upper(currency)),
    constraint chk_fare_class_prices_country_code_upper check (country_code = upper(country_code)),
    constraint chk_fare_class_prices_base_price_non_negative check (base_price >= 0),
    constraint uq_fare_class_prices_scope unique (fare_class_id, currency, country_code)
);

create index if not exists idx_fare_class_prices_currency_country
    on fare_class_prices(currency, country_code);

