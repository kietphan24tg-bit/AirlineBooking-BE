create table booking_contacts (
    id bigint generated by default as identity primary key,
    booking_id bigint not null references bookings(id),
    email varchar(255),
    phone varchar(30),
    is_primary boolean not null default false,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint chk_booking_contacts_has_channel
        check (email is not null or phone is not null)
);

create index idx_booking_contacts_booking_id on booking_contacts(booking_id);
create unique index uq_booking_contacts_primary
    on booking_contacts(booking_id)
    where is_primary;
