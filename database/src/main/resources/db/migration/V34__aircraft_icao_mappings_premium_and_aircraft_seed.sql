-- Seat classes: only ECONOMY + BUSINESS on layouts; PREMIUM_ECONOMY fares -> ECONOMY seats in V35.
-- ICAO type designator -> internal aircraft (see FlightImportService)
create table if not exists aircraft_icao_mappings (
    id bigint generated by default as identity primary key,
    icao_code varchar(10) not null,
    aircraft_id bigint not null references aircraft (id) on delete restrict,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint uq_aircraft_icao_mappings_icao unique (icao_code)
);

create index if not exists idx_aircraft_icao_mappings_aircraft_id
    on aircraft_icao_mappings (aircraft_id);

-- New aircraft + layouts (common AirLabs / industry type codes).
-- V2 aircraft has no unique on model; skip rows that already exist by name.
insert into aircraft (model, manufacturer, total_seats, created_at, updated_at)
select v.model, v.manufacturer, v.total_seats, current_timestamp, current_timestamp
from (
    values ('A320neo', 'Airbus', 192),
           ('Boeing 737-800', 'Boeing', 198),
           ('ATR 72-600', 'ATR', 96),
           ('Embraer E190', 'Embraer', 100)
) as v (model, manufacturer, total_seats)
where not exists (select 1 from aircraft a where a.model = v.model);

insert into aircraft_layout (aircraft_id, total_rows, columns, business_rows, created_at)
select a.id, v.total_rows, v.columns, v.business_rows, current_timestamp
from aircraft a
join (
    values ('A320neo', 32, 'ABCDEF', 3),
           ('Boeing 737-800', 33, 'ABCDEF', 3),
           ('ATR 72-600', 24, 'ABCD', 0),
           ('Embraer E190', 25, 'ABCD', 4)
) as v (model, total_rows, columns, business_rows)
  on v.model = a.model
where not exists (
    select 1 from aircraft_layout al where al.aircraft_id = a.id
);

-- Layout cabin zones (BUSINESS / ECONOMY) for new layouts only
insert into aircraft_layout_zones (aircraft_layout_id, seat_class_id, row_start, row_end, columns)
select al.id,
       sc.id,
       1,
       greatest(1, least(al.business_rows, al.total_rows)),
       null
from aircraft_layout al
join aircraft a on a.id = al.aircraft_id
join seat_classes sc on sc.code = 'BUSINESS'
where a.model in ('A320neo', 'Boeing 737-800', 'Embraer E190')
  and al.business_rows > 0
  and not exists (
    select 1
    from aircraft_layout_zones z
    where z.aircraft_layout_id = al.id
      and z.seat_class_id = sc.id
      and z.row_start = 1
      and z.row_end = greatest(1, least(al.business_rows, al.total_rows))
      and z.columns is null
  );

insert into aircraft_layout_zones (aircraft_layout_id, seat_class_id, row_start, row_end, columns)
select al.id,
       sc.id,
       greatest(1, al.business_rows + 1),
       al.total_rows,
       null
from aircraft_layout al
join aircraft a on a.id = al.aircraft_id
join seat_classes sc on sc.code = 'ECONOMY'
where a.model in ('A320neo', 'Boeing 737-800', 'ATR 72-600', 'Embraer E190')
  and al.total_rows > al.business_rows
  and not exists (
    select 1
    from aircraft_layout_zones z
    where z.aircraft_layout_id = al.id
      and z.seat_class_id = sc.id
      and z.row_start = greatest(1, al.business_rows + 1)
      and z.row_end = al.total_rows
      and z.columns is null
  );

-- Seat type zones: ABCDEF layouts (A320neo, B737-800)
insert into aircraft_layout_seat_type_zones (aircraft_layout_id, seat_type_id, row_start, row_end, columns)
select al.id, st.id, 1, al.total_rows, 'A,F'
from aircraft_layout al
join aircraft a on a.id = al.aircraft_id
join seat_types st on st.code = 'WINDOW'
where a.model in ('A320neo', 'Boeing 737-800')
  and regexp_replace(upper(coalesce(al.columns, '')), '[^A-Z]', '', 'g') = 'ABCDEF'
on conflict do nothing;

insert into aircraft_layout_seat_type_zones (aircraft_layout_id, seat_type_id, row_start, row_end, columns)
select al.id, st.id, 1, al.total_rows, 'C,D'
from aircraft_layout al
join aircraft a on a.id = al.aircraft_id
join seat_types st on st.code = 'AISLE'
where a.model in ('A320neo', 'Boeing 737-800')
  and regexp_replace(upper(coalesce(al.columns, '')), '[^A-Z]', '', 'g') = 'ABCDEF'
on conflict do nothing;

insert into aircraft_layout_seat_type_zones (aircraft_layout_id, seat_type_id, row_start, row_end, columns)
select al.id, st.id, 1, al.total_rows, 'B,E'
from aircraft_layout al
join aircraft a on a.id = al.aircraft_id
join seat_types st on st.code = 'MIDDLE'
where a.model in ('A320neo', 'Boeing 737-800')
  and regexp_replace(upper(coalesce(al.columns, '')), '[^A-Z]', '', 'g') = 'ABCDEF'
on conflict do nothing;

-- Mappings (uppercase ICAO type codes)
insert into aircraft_icao_mappings (icao_code, aircraft_id, created_at, updated_at)
select m.icao, a.id, current_timestamp, current_timestamp
from (values
          ('A320', 'A320-200'),
          ('A20N', 'A320neo'),
          ('A321', 'A321-200'),
          ('A21N', 'A321neo'),
          ('B789', 'B787-9'),
          ('A359', 'A350-900'),
          ('A333', 'A330-300'),
          ('B738', 'Boeing 737-800'),
          ('AT76', 'ATR 72-600'),
          ('E190', 'Embraer E190')
     ) as m (icao, model)
join aircraft a on a.model = m.model
on conflict (icao_code) do update
    set aircraft_id   = excluded.aircraft_id,
        updated_at    = excluded.updated_at;
