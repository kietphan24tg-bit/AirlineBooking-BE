create table if not exists aircraft_layout_seat_type_zones (
    id bigint generated by default as identity primary key,
    aircraft_layout_id bigint not null references aircraft_layout(id) on delete cascade,
    seat_type_id bigint not null references seat_types(id),
    row_start integer not null,
    row_end integer not null,
    columns varchar(20),
    constraint chk_aircraft_layout_seat_type_zones_row_range
        check (row_start > 0 and row_end >= row_start),
    constraint uq_aircraft_layout_seat_type_zones
        unique (aircraft_layout_id, seat_type_id, row_start, row_end, columns)
);

create index if not exists idx_layout_seat_type_zones_layout_id
    on aircraft_layout_seat_type_zones(aircraft_layout_id);

create index if not exists idx_layout_seat_type_zones_layout_rows
    on aircraft_layout_seat_type_zones(aircraft_layout_id, row_start, row_end);

insert into aircraft_layout_seat_type_zones (aircraft_layout_id, seat_type_id, row_start, row_end, columns)
select al.id, st.id, 1, al.total_rows, 'A,F'
from aircraft_layout al
join seat_types st on st.code = 'WINDOW'
where al.columns = 'ABCDEF'
on conflict do nothing;

