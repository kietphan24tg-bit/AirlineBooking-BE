create table user_recent_airports (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    airport_id bigint not null,
    usage_type varchar(30) not null,
    last_used_at timestamp with time zone not null default current_timestamp,
    search_count integer not null default 1,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_user_recent_airports_user
        foreign key (user_id) references users(id) on delete cascade,
    constraint fk_user_recent_airports_airport
        foreign key (airport_id) references airports(id) on delete cascade,
    constraint uq_user_recent_airports_user_airport_usage
        unique (user_id, airport_id, usage_type),
    constraint chk_user_recent_airports_usage_type
        check (usage_type in ('DEPARTURE', 'ARRIVAL'))
);

create index idx_user_recent_airports_user_last_used
    on user_recent_airports(user_id, last_used_at desc);

