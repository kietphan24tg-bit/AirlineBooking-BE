create table if not exists ticket_financial_snapshots (
    id bigint generated by default as identity primary key,
    booking_id bigint not null references bookings(id),
    ticket_id bigint not null unique references tickets(id),
    passenger_id bigint not null references passengers(id),
    fare_gross_amount numeric(18, 2) not null,
    promo_allocated_amount numeric(18, 2) not null,
    fare_net_amount numeric(18, 2) not null,
    seat_refund_amount numeric(18, 2) not null,
    service_refund_amount numeric(18, 2) not null,
    refund_fee_amount numeric(18, 2) not null,
    is_refundable boolean not null,
    passenger_type varchar(20) not null,
    currency varchar(10) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_ticket_financial_snapshots_booking_id
    on ticket_financial_snapshots(booking_id);

create index if not exists idx_ticket_financial_snapshots_passenger_id
    on ticket_financial_snapshots(passenger_id);

create table if not exists booking_cancellations (
    id bigint generated by default as identity primary key,
    booking_id bigint not null references bookings(id),
    payment_id bigint not null references payments(id),
    requested_by_user_id bigint not null references users(id),
    idempotency_key varchar(255) not null,
    request_hash varchar(64) not null,
    reason varchar(255),
    provider varchar(30) not null,
    provider_refund_id varchar(255),
    provider_status varchar(50),
    refund_status varchar(30) not null,
    error_code varchar(80),
    error_message varchar(255),
    currency varchar(10) not null,
    fare_gross_total numeric(18, 2) not null,
    promo_allocated_total numeric(18, 2) not null,
    fare_net_total numeric(18, 2) not null,
    seat_refund_total numeric(18, 2) not null,
    service_refund_total numeric(18, 2) not null,
    refund_fee_total numeric(18, 2) not null,
    net_refund_total numeric(18, 2) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    processed_at timestamp with time zone,
    constraint uq_booking_cancellations_idempotency unique (booking_id, idempotency_key),
    constraint chk_booking_cancellations_refund_status
        check (refund_status in ('PENDING', 'SUCCEEDED', 'FAILED'))
);

create index if not exists idx_booking_cancellations_booking_id
    on booking_cancellations(booking_id, created_at desc);

create index if not exists idx_booking_cancellations_payment_id
    on booking_cancellations(payment_id, created_at desc);

create table if not exists booking_cancellation_items (
    id bigint generated by default as identity primary key,
    cancellation_id bigint not null references booking_cancellations(id) on delete cascade,
    ticket_id bigint not null references tickets(id),
    passenger_id bigint not null references passengers(id),
    fare_gross_amount numeric(18, 2) not null,
    promo_allocated_amount numeric(18, 2) not null,
    fare_net_amount numeric(18, 2) not null,
    seat_refund_amount numeric(18, 2) not null,
    service_refund_amount numeric(18, 2) not null,
    refund_fee_amount numeric(18, 2) not null,
    net_refund_amount numeric(18, 2) not null,
    created_at timestamp with time zone not null default current_timestamp,
    constraint uq_booking_cancellation_items_ticket unique (cancellation_id, ticket_id)
);

create index if not exists idx_booking_cancellation_items_cancellation_id
    on booking_cancellation_items(cancellation_id);
