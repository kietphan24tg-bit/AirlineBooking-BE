create table if not exists seat_change_settlements (
    id bigint generated by default as identity primary key,
    booking_id bigint not null references bookings(id),
    preview_token varchar(120),
    idempotency_key varchar(120),
    settlement_type varchar(30) not null,
    status varchar(30) not null,
    additional_amount numeric(18, 2) not null,
    refund_amount numeric(18, 2) not null,
    net_amount numeric(18, 2) not null,
    currency varchar(10) not null,
    provider varchar(30),
    provider_refund_id varchar(255),
    error_code varchar(80),
    error_message varchar(500),
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_seat_change_settlements_booking_id
    on seat_change_settlements(booking_id, created_at desc);

create table if not exists seat_change_settlement_items (
    id bigint generated by default as identity primary key,
    settlement_id bigint not null references seat_change_settlements(id) on delete cascade,
    passenger_id bigint not null,
    flight_id bigint not null,
    from_seat_id bigint,
    from_seat_number varchar(10),
    to_seat_id bigint,
    to_seat_number varchar(10),
    old_amount numeric(18, 2) not null,
    new_amount numeric(18, 2) not null,
    delta_amount numeric(18, 2) not null
);

create index if not exists idx_seat_change_settlement_items_settlement_id
    on seat_change_settlement_items(settlement_id);

alter table payments
    add column if not exists seat_change_settlement_id bigint references seat_change_settlements(id);

create index if not exists idx_payments_seat_change_settlement_id
    on payments(seat_change_settlement_id);
