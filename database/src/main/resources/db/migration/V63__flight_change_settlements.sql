create table if not exists flight_change_settlements (
    id bigint generated by default as identity primary key,
    booking_id bigint not null references bookings(id),
    quote_token varchar(120),
    idempotency_key varchar(120),
    current_flight_id bigint not null,
    new_flight_id bigint not null,
    new_fare_id bigint not null,
    settlement_type varchar(30) not null,
    status varchar(30) not null,
    additional_amount numeric(18, 2) not null,
    refund_amount numeric(18, 2) not null,
    net_amount numeric(18, 2) not null,
    currency varchar(10) not null,
    provider varchar(30),
    provider_refund_id varchar(255),
    provider_payment_reference varchar(255),
    error_code varchar(80),
    error_message varchar(500),
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_flight_change_settlements_booking_id
    on flight_change_settlements(booking_id, created_at desc);

create table if not exists flight_change_settlement_items (
    id bigint generated by default as identity primary key,
    settlement_id bigint not null references flight_change_settlements(id) on delete cascade,
    ticket_id bigint not null,
    passenger_id bigint not null,
    passenger_name varchar(255),
    passenger_type varchar(20),
    original_fare_amount numeric(18, 2) not null,
    new_fare_amount numeric(18, 2) not null,
    fare_difference numeric(18, 2) not null,
    change_fee numeric(18, 2) not null,
    tax_difference numeric(18, 2) not null,
    net_amount numeric(18, 2) not null
);

create index if not exists idx_flight_change_settlement_items_settlement_id
    on flight_change_settlement_items(settlement_id);

alter table payments
    add column if not exists flight_change_settlement_id bigint references flight_change_settlements(id);

create index if not exists idx_payments_flight_change_settlement_id
    on payments(flight_change_settlement_id);
