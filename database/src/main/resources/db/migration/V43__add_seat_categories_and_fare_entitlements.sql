create table if not exists seat_categories (
    id bigint generated by default as identity primary key,
    code varchar(30) not null unique,
    name varchar(100) not null,
    pricing_rank integer not null,
    surcharge_amount numeric(18, 2) not null default 0,
    constraint chk_seat_categories_pricing_rank_positive check (pricing_rank > 0),
    constraint chk_seat_categories_surcharge_non_negative check (surcharge_amount >= 0)
);

insert into seat_categories (code, name, pricing_rank, surcharge_amount)
values ('STANDARD', 'Standard', 1, 0.00),
       ('PREFERRED', 'Preferred', 2, 40000.00),
       ('EXIT_ROW', 'Exit Row', 3, 120000.00),
       ('EXTRA_LEGROOM', 'Extra Legroom', 4, 180000.00)
on conflict (code) do update
set name = excluded.name,
    pricing_rank = excluded.pricing_rank,
    surcharge_amount = excluded.surcharge_amount;

create table if not exists aircraft_layout_seat_category_zones (
    id bigint generated by default as identity primary key,
    aircraft_layout_id bigint not null references aircraft_layout(id) on delete cascade,
    seat_category_id bigint not null references seat_categories(id),
    row_start integer not null,
    row_end integer not null,
    columns varchar(20),
    constraint chk_aircraft_layout_seat_category_zones_row_range
        check (row_start > 0 and row_end >= row_start),
    constraint uq_aircraft_layout_seat_category_zones
        unique (aircraft_layout_id, seat_category_id, row_start, row_end, columns)
);

create index if not exists idx_layout_seat_category_zones_layout_id
    on aircraft_layout_seat_category_zones(aircraft_layout_id);

create index if not exists idx_layout_seat_category_zones_layout_rows
    on aircraft_layout_seat_category_zones(aircraft_layout_id, row_start, row_end);

alter table flight_seats
    add column if not exists seat_category_id bigint references seat_categories(id);

update flight_seats fs
set seat_category_id = sc.id
from seat_categories sc
where fs.seat_category_id is null
  and sc.code = 'STANDARD';

alter table flight_seats
    alter column seat_category_id set not null;

create index if not exists idx_flight_seats_seat_category_id on flight_seats(seat_category_id);

alter table fare_classes
    add column if not exists included_seat_category_id bigint references seat_categories(id);

update seat_types
set surcharge_amount =
    case
        when code = 'MIDDLE' then 0.00
        when code in ('WINDOW', 'AISLE') then 20000.00
        else surcharge_amount
    end;

update fare_classes fc
set seat_selection_policy =
    case
        when fc.code = 'ECONOMY' then 'PAID'
        when fc.code in ('PREMIUM', 'BUSINESS', 'FIRST', 'ECONOMY_FLEX') then 'INCLUDED'
        when fc.seat_selection then 'INCLUDED'
        else 'NOT_ALLOWED'
    end,
    included_seat_category_id = sc.id
from seat_categories sc
where ((fc.code = 'PREMIUM' or fc.code = 'ECONOMY_FLEX') and sc.code = 'STANDARD')
   or (fc.code in ('BUSINESS', 'FIRST') and sc.code = 'EXTRA_LEGROOM');

update fare_classes
set included_seat_category_id = null
where code = 'ECONOMY';

insert into aircraft_layout_seat_category_zones (aircraft_layout_id, seat_category_id, row_start, row_end, columns)
select al.id,
       sc.id,
       al.business_rows + 1,
       al.business_rows + 1,
       null
from aircraft_layout al
join seat_categories sc on sc.code = 'EXTRA_LEGROOM'
where al.total_rows > al.business_rows
  and not exists (
      select 1
      from aircraft_layout_seat_category_zones z
      where z.aircraft_layout_id = al.id
        and z.seat_category_id = sc.id
        and z.row_start = al.business_rows + 1
        and z.row_end = al.business_rows + 1
        and z.columns is null
  );

insert into aircraft_layout_seat_category_zones (aircraft_layout_id, seat_category_id, row_start, row_end, columns)
select al.id,
       sc.id,
       al.business_rows + 2,
       least(al.total_rows, al.business_rows + 3),
       null
from aircraft_layout al
join seat_categories sc on sc.code = 'PREFERRED'
where al.total_rows >= al.business_rows + 2
  and not exists (
      select 1
      from aircraft_layout_seat_category_zones z
      where z.aircraft_layout_id = al.id
        and z.seat_category_id = sc.id
        and z.row_start = al.business_rows + 2
        and z.row_end = least(al.total_rows, al.business_rows + 3)
        and z.columns is null
  );

insert into aircraft_layout_seat_category_zones (aircraft_layout_id, seat_category_id, row_start, row_end, columns)
select al.id,
       sc.id,
       al.business_rows + greatest(4, ((al.total_rows - al.business_rows) / 2)),
       al.business_rows + greatest(4, ((al.total_rows - al.business_rows) / 2)),
       null
from aircraft_layout al
join seat_categories sc on sc.code = 'EXIT_ROW'
where al.total_rows >= al.business_rows + 6
  and not exists (
      select 1
      from aircraft_layout_seat_category_zones z
      where z.aircraft_layout_id = al.id
        and z.seat_category_id = sc.id
        and z.row_start = al.business_rows + greatest(4, ((al.total_rows - al.business_rows) / 2))
        and z.row_end = al.business_rows + greatest(4, ((al.total_rows - al.business_rows) / 2))
        and z.columns is null
  );
