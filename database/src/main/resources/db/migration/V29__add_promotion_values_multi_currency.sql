create table if not exists promotion_values (
    id bigint generated by default as identity primary key,
    promotion_id bigint not null references promotions(id) on delete cascade,
    currency varchar(3) not null,
    country_code varchar(2) not null default 'GL',
    fixed_discount_value numeric(18, 2),
    max_discount_value numeric(18, 2),
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint chk_promotion_values_currency_upper check (currency = upper(currency)),
    constraint chk_promotion_values_country_code_upper check (country_code = upper(country_code)),
    constraint chk_promotion_values_fixed_non_negative check (fixed_discount_value is null or fixed_discount_value >= 0),
    constraint chk_promotion_values_max_non_negative check (max_discount_value is null or max_discount_value >= 0),
    constraint chk_promotion_values_at_least_one_value
        check (fixed_discount_value is not null or max_discount_value is not null),
    constraint uq_promotion_values_scope unique (promotion_id, currency, country_code)
);

create index if not exists idx_promotion_values_currency_country
    on promotion_values(currency, country_code);

