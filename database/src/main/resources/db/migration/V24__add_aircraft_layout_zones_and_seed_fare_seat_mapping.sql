create table if not exists aircraft_layout_zones (
    id bigint generated by default as identity primary key,
    aircraft_layout_id bigint not null references aircraft_layout(id) on delete cascade,
    seat_class_id bigint not null references seat_classes(id),
    row_start integer not null,
    row_end integer not null,
    columns varchar(20),
    constraint chk_aircraft_layout_zones_row_range check (row_start > 0 and row_end >= row_start)
);

create index if not exists idx_aircraft_layout_zones_layout_id
    on aircraft_layout_zones(aircraft_layout_id);

create index if not exists idx_aircraft_layout_zones_layout_rows
    on aircraft_layout_zones(aircraft_layout_id, row_start, row_end);

insert into aircraft_layout_zones (aircraft_layout_id, seat_class_id, row_start, row_end, columns)
select al.id,
       sc.id,
       1,
       greatest(1, least(al.business_rows, al.total_rows)),
       null
from aircraft_layout al
join seat_classes sc on sc.code = 'BUSINESS'
where al.business_rows > 0
  and not exists (
    select 1
    from aircraft_layout_zones z
    where z.aircraft_layout_id = al.id
      and z.seat_class_id = sc.id
      and z.row_start = 1
      and z.row_end = greatest(1, least(al.business_rows, al.total_rows))
      and z.columns is null
  );

insert into aircraft_layout_zones (aircraft_layout_id, seat_class_id, row_start, row_end, columns)
select al.id,
       sc.id,
       greatest(1, al.business_rows + 1),
       al.total_rows,
       null
from aircraft_layout al
join seat_classes sc on sc.code = 'ECONOMY'
where al.total_rows > al.business_rows
  and not exists (
    select 1
    from aircraft_layout_zones z
    where z.aircraft_layout_id = al.id
      and z.seat_class_id = sc.id
      and z.row_start = greatest(1, al.business_rows + 1)
      and z.row_end = al.total_rows
      and z.columns is null
  );

insert into fare_class_seat_classes (fare_class_id, seat_class_id)
select fc.id,
       sc.id
from fare_classes fc
join seat_classes sc
  on sc.code = case fc.cabin_class
                 when 'ECONOMY' then 'ECONOMY'
                 when 'PREMIUM_ECONOMY' then 'PREMIUM'
                 when 'BUSINESS' then 'BUSINESS'
                 when 'FIRST' then 'BUSINESS'
                 else 'ECONOMY'
               end
on conflict (fare_class_id, seat_class_id) do nothing;
