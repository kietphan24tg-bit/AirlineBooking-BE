create table refresh_token_sessions (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    refresh_token text not null,
    revoked boolean not null default false,
    expires_at timestamp with time zone not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_refresh_token_sessions_user
        foreign key (user_id) references users(id) on delete cascade,
    constraint uq_refresh_token_sessions_token
        unique (refresh_token)
);

create index idx_refresh_token_sessions_user_revoked
    on refresh_token_sessions(user_id, revoked);

create index idx_refresh_token_sessions_expires_at
    on refresh_token_sessions(expires_at);
