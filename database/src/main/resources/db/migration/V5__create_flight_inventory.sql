create table flight_fares (
    id bigint generated by default as identity primary key,
    flight_id bigint not null references flights(id),
    fare_class_id bigint not null references fare_classes(id),
    base_price numeric(18, 2) not null,
    tax_breakdown jsonb,
    total_tax_amount numeric(18, 2) not null default 0,
    total_price numeric(18, 2) not null,
    available_seats integer not null default 0,
    status varchar(20) not null,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint uq_flight_fares_flight_fare_class unique (flight_id, fare_class_id)
);

create table flight_seats (
    id bigint generated by default as identity primary key,
    flight_id bigint not null references flights(id),
    seat_id bigint not null references seats(id),
    status varchar(20) not null,
    price numeric(18, 2) not null default 0,
    fare_class_id bigint references fare_classes(id),
    passenger_id bigint references passengers(id),
    booking_id bigint references bookings(id),
    reserved_until timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    constraint uq_flight_seats_flight_seat unique (flight_id, seat_id)
);
