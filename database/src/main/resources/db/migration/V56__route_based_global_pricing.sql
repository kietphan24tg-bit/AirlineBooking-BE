create table if not exists pricing_market_profiles (
    country_code varchar(2) primary key,
    currency varchar(3) not null,
    allow_first boolean not null default false,
    tax_profile_code varchar(50) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint chk_pricing_market_profiles_country_upper check (country_code = upper(country_code)),
    constraint chk_pricing_market_profiles_currency_upper check (currency = upper(currency))
);

create table if not exists market_base_prices (
    id bigint generated by default as identity primary key,
    origin_country_code varchar(2) not null,
    destination_country_code varchar(2) not null,
    currency varchar(3) not null,
    base_economy_price numeric(18, 2) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint chk_market_base_prices_origin_upper check (origin_country_code = upper(origin_country_code)),
    constraint chk_market_base_prices_destination_upper check (destination_country_code = upper(destination_country_code)),
    constraint chk_market_base_prices_currency_upper check (currency = upper(currency)),
    constraint chk_market_base_prices_amount_non_negative check (base_economy_price >= 0),
    constraint uq_market_base_prices_scope unique (origin_country_code, destination_country_code, currency)
);

create index if not exists idx_market_base_prices_origin_destination
    on market_base_prices(origin_country_code, destination_country_code);

create table if not exists route_base_prices (
    id bigint generated by default as identity primary key,
    origin_airport_code varchar(3) not null,
    destination_airport_code varchar(3) not null,
    currency varchar(3) not null,
    base_economy_price numeric(18, 2) not null,
    active_from date,
    active_until date,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint chk_route_base_prices_origin_upper check (origin_airport_code = upper(origin_airport_code)),
    constraint chk_route_base_prices_destination_upper check (destination_airport_code = upper(destination_airport_code)),
    constraint chk_route_base_prices_currency_upper check (currency = upper(currency)),
    constraint chk_route_base_prices_amount_non_negative check (base_economy_price >= 0),
    constraint chk_route_base_prices_valid_window check (active_until is null or active_from is null or active_until >= active_from),
    constraint uq_route_base_prices_scope unique (origin_airport_code, destination_airport_code, currency)
);

create index if not exists idx_route_base_prices_origin_destination
    on route_base_prices(origin_airport_code, destination_airport_code);

create table if not exists fare_class_multipliers (
    id bigint generated by default as identity primary key,
    fare_code varchar(30) not null,
    trip_scope varchar(20) not null,
    multiplier numeric(10, 4) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint chk_fare_class_multipliers_fare_upper check (fare_code = upper(fare_code)),
    constraint chk_fare_class_multipliers_scope_upper check (trip_scope = upper(trip_scope)),
    constraint chk_fare_class_multipliers_positive check (multiplier > 0),
    constraint uq_fare_class_multipliers_scope unique (fare_code, trip_scope)
);

create index if not exists idx_fare_class_multipliers_fare_scope
    on fare_class_multipliers(fare_code, trip_scope);

