    insert into pricing_market_profiles (country_code, currency, allow_first, tax_profile_code, created_at, updated_at)
    select country_code, currency, allow_first, tax_profile_code, current_timestamp, current_timestamp
    from market_profiles
    on conflict (country_code) do update
    set
        currency = excluded.currency,
        allow_first = excluded.allow_first,
        tax_profile_code = excluded.tax_profile_code,
        updated_at = current_timestamp
    returning country_code, currency
)
insert into market_base_prices (origin_country_code, destination_country_code, currency, base_economy_price, created_at, updated_at)
select
    o.country_code,
    d.country_code,
    o.currency,
    round(
        case
            when o.country_code = d.country_code then o.domestic_base
            else o.domestic_base * 1.65
        end,
        2
    ) as base_economy_price,
    current_timestamp,
    current_timestamp
from market_profiles o
cross join market_profiles d
on conflict (origin_country_code, destination_country_code, currency) do update
set
    base_economy_price = excluded.base_economy_price,
    updated_at = current_timestamp;

